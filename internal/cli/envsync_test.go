func TestIsKubeInjected(t *testing.T) {
	tests := []struct {
		name     string
		envName  string
		injected bool
	}{
		{"kubernetes service host", "KUBERNETES_SERVICE_HOST", true},
		{"kubernetes service port", "KUBERNETES_SERVICE_PORT", true},
		{"kubernetes port", "KUBERNETES_PORT", true},
		{"service host pattern", "PAYMENTS_API_SERVICE_HOST", true},
		{"service port pattern", "PAYMENTS_API_SERVICE_PORT", true},
		{"port pattern", "PAYMENTS_API_PORT_8080_TCP", true},
		{"home", "HOME", true},
		{"hostname", "HOSTNAME", true},
		{"path", "PATH", true},
		{"app env", "DATABASE_URL", false},
		{"app env", "APP_VERSION", false},
		{"app env", "ACCOUNTS_API_URL", false},
		{"app env", "REDIS_URL", false},
		{"app env with port word", "SERVER_PORT", false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := isKubeInjected(tt.envName)
			assert.Equal(t, tt.injected, got, "isKubeInjected(%q)", tt.envName)
		})
	}
}

func TestSyncBaselineEnv(t *testing.T) {
	ctx := context.Background()

	pod := &corev1.Pod{
		ObjectMeta: metav1.ObjectMeta{
			Name:      "payments-api-abc123",
			Namespace: "demo-bank",
			Labels: map[string]string{
				"app":             "payments-api",
				"diverge.io/role": "baseline",
			},
		},
		Spec: corev1.PodSpec{
			Containers: []corev1.Container{
				{
					Name:  "payments-api",
					Image: "payments-api:latest",
					Env: []corev1.EnvVar{
						{Name: "DATABASE_URL", Value: "postgres://localhost:5432/mydb"},
						{Name: "APP_VERSION", Value: "v1.2.3"},
						{Name: "ACCOUNTS_API_URL", Value: "http://accounts-api:8080"},
						{Name: "KUBERNETES_SERVICE_HOST", Value: "10.0.0.1"},
						{Name: "KUBERNETES_SERVICE_PORT", Value: "443"},
						{Name: "PAYMENTS_API_SERVICE_HOST", Value: "10.0.0.5"},
						{Name: "HOME", Value: "/root"},
						{Name: "PATH", Value: "/usr/local/bin:/usr/bin"},
						{
							Name: "SECRET_VAR",
							ValueFrom: &corev1.EnvVarSource{
								SecretKeyRef: &corev1.SecretKeySelector{
									LocalObjectReference: corev1.LocalObjectReference{Name: "my-secret"},
									Key:                  "api-key",
								},
							},
						},
					},
				},
			},
		},
	}

	clientset := fake.NewSimpleClientset(pod)

	tmpDir := t.TempDir()
	outPath := filepath.Join(tmpDir, ".env.diverge")

	synced, err := syncBaselineEnv(ctx, clientset, syncEnvOptions{
		Namespace:   "demo-bank",
		ServiceName: "payments-api",
		OutputPath:  outPath,
	})
	require.NoError(t, err)
	assert.Equal(t, 3, synced, "should sync 3 app env vars (DATABASE_URL, APP_VERSION, ACCOUNTS_API_URL)")

	content, err := os.ReadFile(outPath)
	require.NoError(t, err)
	contentStr := string(content)

	// Should contain app env vars
	assert.Contains(t, contentStr, "DATABASE_URL=postgres://localhost:5432/mydb")
	assert.Contains(t, contentStr, "APP_VERSION=v1.2.3")
	assert.Contains(t, contentStr, "ACCOUNTS_API_URL=http://accounts-api:8080")

	// Should NOT contain K8s-injected vars
	assert.NotContains(t, contentStr, "KUBERNETES_SERVICE_HOST")
	assert.NotContains(t, contentStr, "PAYMENTS_API_SERVICE_HOST")
	assert.NotContains(t, contentStr, "\nHOME=")
	assert.NotContains(t, contentStr, "\nPATH=")

	// Should have commented-out secret reference
	assert.Contains(t, contentStr, "# SECRET_VAR=# sourced from secret:my-secret/api-key")

	// Should have header comment
	assert.Contains(t, contentStr, "Generated by 'diverge dev'")

	// File should be 0600
	info, err := os.Stat(outPath)
	require.NoError(t, err)
	assert.Equal(t, os.FileMode(0600), info.Mode().Perm(), "file should be owner-only readable")
}

