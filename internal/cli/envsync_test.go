func TestSyncBaselineEnv_EnvFrom(t *testing.T) {
	ctx := context.Background()

	pod := &corev1.Pod{
		ObjectMeta: metav1.ObjectMeta{
			Name:      "svc-envfrom",
			Namespace: "default",
			Labels:    map[string]string{"app": "svc-envfrom"},
		},
		Spec: corev1.PodSpec{
			Containers: []corev1.Container{
				{
					Name:  "svc",
					Image: "svc:latest",
					EnvFrom: []corev1.EnvFromSource{
						{
							ConfigMapRef: &corev1.ConfigMapEnvSource{
								LocalObjectReference: corev1.LocalObjectReference{Name: "app-settings"},
							},
						},
						{
							SecretRef: &corev1.SecretEnvSource{
								LocalObjectReference: corev1.LocalObjectReference{Name: "db-creds"},
							},
						},
					},
				},
			},
		},
	}

	clientset := fake.NewSimpleClientset(pod)
	tmpDir := t.TempDir()
	outPath := filepath.Join(tmpDir, ".env.diverge")

	synced, err := syncBaselineEnv(ctx, clientset, syncEnvOptions{
		Namespace:   "default",
		ServiceName: "svc-envfrom",
		OutputPath:  outPath,
	})
	require.NoError(t, err)
	assert.Equal(t, 0, synced, "envFrom annotations are not counted as synced vars")

	content, err := os.ReadFile(outPath)
	require.NoError(t, err)
	contentStr := string(content)

	// Should have envFrom annotations
	assert.Contains(t, contentStr, "# [envFrom] configmap:app-settings")
	assert.Contains(t, contentStr, "# [envFrom] secret:db-creds")
	// File should still be written (not skipped)
	assert.Contains(t, contentStr, "Generated by 'diverge dev'")
}

func TestSyncBaselineEnv_StaleFileTruncated(t *testing.T) {
	ctx := context.Background()

	// Pod with no env vars at all
	pod := &corev1.Pod{
		ObjectMeta: metav1.ObjectMeta{
			Name:      "empty-svc-abc",
			Namespace: "default",
			Labels:    map[string]string{"app": "empty-svc"},
		},
		Spec: corev1.PodSpec{
			Containers: []corev1.Container{
				{
					Name:  "svc",
					Image: "svc:latest",
					// No Env or EnvFrom
				},
			},
		},
	}

	clientset := fake.NewSimpleClientset(pod)
	tmpDir := t.TempDir()
	outPath := filepath.Join(tmpDir, ".env.diverge")

	// Write stale content first
	require.NoError(t, os.WriteFile(outPath, []byte("STALE_VAR=old_value\n"), 0600))

	synced, err := syncBaselineEnv(ctx, clientset, syncEnvOptions{
		Namespace:   "default",
		ServiceName: "empty-svc",
		OutputPath:  outPath,
	})
	require.NoError(t, err)
	assert.Equal(t, 0, synced)

	// Stale content should be replaced with header-only file
	content, err := os.ReadFile(outPath)
	require.NoError(t, err)
	contentStr := string(content)
	assert.NotContains(t, contentStr, "STALE_VAR")
	assert.Contains(t, contentStr, "Generated by 'diverge dev'")
}

func TestDescribeValueSource(t *testing.T) {
	tests := []struct {
		name     string
		source   *corev1.EnvVarSource
		contains string
	}{
		{
			"secret",
			&corev1.EnvVarSource{SecretKeyRef: &corev1.SecretKeySelector{
				LocalObjectReference: corev1.LocalObjectReference{Name: "db-creds"},
				Key:                  "password",
			}},
			"secret:db-creds/password",
		},
		{
			"configmap",
			&corev1.EnvVarSource{ConfigMapKeyRef: &corev1.ConfigMapKeySelector{
				LocalObjectReference: corev1.LocalObjectReference{Name: "settings"},
				Key:                  "log-level",
			}},
			"configmap:settings/log-level",
		},
		{
			"fieldRef",
			&corev1.EnvVarSource{FieldRef: &corev1.ObjectFieldSelector{FieldPath: "metadata.name"}},
			"fieldRef:metadata.name",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			result := describeValueSource(tt.source)
			assert.True(t, strings.Contains(result, tt.contains), "describeValueSource: got %q, want contains %q", result, tt.contains)
		})
	}
}
